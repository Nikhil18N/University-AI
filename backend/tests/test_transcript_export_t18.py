from pathlib import Path
import pytest
from app.services.chat_service import clean_backticks_and_naming


def test_clean_backticks_plain_prose():
    text = "You can visit `leadingindia.ai` for details, or explore `SRiX` on the `150-acre` campus."
    cleaned = clean_backticks_and_naming(text, user_query="tell me about campus AI and incubator")
    assert "`leadingindia.ai`" not in cleaned
    assert "leadingindia.ai" in cleaned
    assert "`SRiX`" not in cleaned
    assert "SRiX" in cleaned
    assert "`150-acre`" not in cleaned
    assert "150-acre" in cleaned


def test_clean_backticks_preserves_code():
    code_text = "Here is how you define a function:\n```python\ndef hello():\n    return `world`\n```\nUse `print()` to run."
    cleaned = clean_backticks_and_naming(code_text, user_query="write python code")
    assert "```python" in cleaned
    assert "`world`" in cleaned


def test_naming_cleanup_sr_buddy_to_sru_buddy():
    text = "Hi! I am SR Buddy, your guide to SR University. How can SR Buddy help you today?"
    cleaned = clean_backticks_and_naming(text)
    assert "SR Buddy" not in cleaned
    assert "SRU Buddy" in cleaned
    assert cleaned == "Hi! I am SRU Buddy, your guide to SR University. How can SRU Buddy help you today?"


def test_export_template_contains_disclaimer_and_no_official_transcript():
    export_ts_path = Path(__file__).resolve().parent.parent.parent / "frontend" / "src" / "utils" / "exportChat.ts"
    content = export_ts_path.read_text()

    # Must NOT have misleading "Official Transcript"
    assert "<div>Official Transcript</div>" not in content
    assert "Chat transcript" in content

    # Must have explicit disclaimer
    assert "Generated by an AI assistant for information only. This is not an offer or confirmation of admission, fees or scholarship. Please verify on the official portal" in content


def test_persona_prompt_identity_rule():
    persona_path = Path(__file__).resolve().parent.parent.parent / "prompts" / "persona.md"
    content = persona_path.read_text()
    assert 'Your name is "SRU Buddy". Never call yourself "SR Buddy".' in content

